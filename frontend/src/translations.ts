export type Language = 'en' | 'pl'
export type Message = keyof typeof polish

const polishFew: Partial<Record<Message, string>> = {
  '{count} options · least crowded first': '{count} opcje · od najmniejszego tłoku',
  '{count} stop visits exceed your {tolerance}% crowd tolerance.': '{count} wizyty na przystankach przekraczają tolerancję tłoku {tolerance}%.',
  '{count} changes': '{count} przesiadki',
}
const polishPlurals = new Intl.PluralRules('pl')

export function translate(language: Language, message: Message, parameters: Record<string, string | number> = {}): string {
  let template = language === 'pl' ? polish[message] : message
  if (language === 'pl' && typeof parameters.count === 'number' && polishPlurals.select(parameters.count) === 'few') {
    template = polishFew[message] ?? template
  }
  return template.replace(/\{(\w+)\}/g, (_, key: string) => {
    if (parameters[key] === undefined) throw new Error(`Missing translation parameter: ${key}`)
    return String(parameters[key])
  })
}

function isMessage(message: string): message is Message {
  return Object.prototype.hasOwnProperty.call(polish, message)
}

